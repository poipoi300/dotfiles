"""Render Codex's native custom-agent adapters from shared role briefs and metadata."""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import sys

ROLES_DIR = Path(__file__).absolute().parent
STATE_FILE = "codex-adapter-state.json"


def load_claude_renderer():
    # The catalog validation lives in the Claude renderer; reuse it instead of a second copy.
    spec = importlib.util.spec_from_file_location("shared_role_renderer", ROLES_DIR / "sync_claude.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def digest(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def toml_string(value: str) -> str:
    # JSON string escapes are a subset of TOML basic-string escapes.
    return json.dumps(value, ensure_ascii=False)


def render_adapter(role: dict, roles_dir: Path) -> bytes:
    brief = (roles_dir / role["brief"]).absolute().as_posix()
    instructions = (
        "Generated adapter. Maintain the shared role brief and catalog.json; regenerate with sync_codex.py.\n\n"
        f"Read the shared role brief at `{brief}` before acting. Follow its complete input, access, "
        "execution, and output contracts together with the task and repository instructions. "
        "Use only tools available in this runtime. If the brief cannot be read, report that blocker.\n"
    )
    lines = [
        "# Generated by ~/.agents/roles/sync_codex.py; edit the shared role sources instead.",
        f"name = {toml_string(role['name'])}",
        f"description = {toml_string(role['description'])}",
        f"developer_instructions = {toml_string(instructions)}",
    ]
    return ("\n".join(lines) + "\n").encode("utf-8")


def adapter_path(role: dict, agents_dir: Path) -> Path:
    return agents_dir / (Path(role["brief"]).stem + ".toml")


def synchronize(roles_dir: Path, agents_dir: Path, *, write: bool = False) -> int:
    roles = load_claude_renderer().load_catalog(roles_dir)
    outputs = {adapter_path(role, agents_dir): render_adapter(role, roles_dir) for role in roles}
    changed = {path: content for path, content in outputs.items() if not path.exists() or path.read_bytes() != content}
    if not changed:
        print(f"All {len(outputs)} Codex role adapters are current.")
        return 0
    if not write:
        print("Codex role adapters need regeneration: " + ", ".join(path.name for path in changed))
        return 1

    state_path = roles_dir / STATE_FILE
    previous = json.loads(state_path.read_text(encoding="utf-8")) if state_path.exists() else {}
    for path in changed:
        if path.exists() and digest(path.read_bytes()) != previous.get(str(path.absolute())):
            raise ValueError(f"Refusing to overwrite an unrecognized or edited adapter: {path.name}")
    agents_dir.mkdir(parents=True, exist_ok=True)
    for path, content in changed.items():
        path.write_bytes(content)
    state = {str(path.absolute()): digest(content) for path, content in outputs.items()}
    state_path.write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8")
    print(f"Regenerated {len(changed)} Codex role adapters.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--agents-dir", type=Path, default=Path.home() / ".codex/agents")
    parser.add_argument("--write", action="store_true", help="Regenerate recognized adapters; otherwise check only")
    args = parser.parse_args()
    try:
        return synchronize(ROLES_DIR, args.agents_dir, write=args.write)
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"Role adapter error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
